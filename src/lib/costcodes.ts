export const costCodeLabel = (code: string) => COST_CODES.find((c) => c.code === code)?.label ?? "";

/** "703.2" -> "07"; returns null for anything that isn't a Sparrow cost code. */
export function divisionOfCode(code: string): string | null {
  const m = code.trim().match(/^(\d{3,4})\.\d+$/);
  if (!m) return null;
  return String(Math.floor(Number(m[1]) / 100)).padStart(2, "0");
}

export const isCostCode = (code: string) => COST_CODES.some((c) => c.code === code.trim());

/** Compact list of codes for a set of divisions, for the estimating prompt. */
export function costCodeList(divisions: string[]) {
  return SPARROW_DIVISIONS.filter((d) => divisions.includes(d.code))
    .map((d) => `Division ${Number(d.code)} ${d.name}: ` + COST_CODES.filter((c) => c.division === d.code).map((c) => `${c.code} ${c.label}`).join("; "))
    .join("\n");
}
